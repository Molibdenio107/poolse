-- Up Migration

-- POOLSE-114: a meet's results arrive by email.
--
-- **One address per club.** `resultados-<token>@<INBOUND_DOMAIN>`, the token on
-- `organization.meet_inbox_token`: 20 characters of [a-z0-9], lowercase because
-- a mail system is free to fold the case of a local part and a token that
-- survived only in one case would be one that silently stopped working.
-- Regenerating it is a club write (owner or admin, audited) — the old address
-- stops at once, because nothing else remembers it.
--
-- **The one read before a tenant is known** is `meet_inbox_organization()`, a
-- definer function that takes the token and answers the club's id and nothing
-- else — the `public_water_page()` pattern, never "look the tenant up, then
-- `withOrg`". It answers null for a club with the competition module off, or
-- one that is archived, suspended or read-only, so mail to such a club is
-- dropped exactly as mail to a token nobody holds.
--
-- **A message is a row, and so is each file it carried.** `meet_inbox_message`
-- is the idempotency key — the provider's message id, once per club — and the
-- record of a sender who sent nothing usable (so the reply goes once).
-- `meet_inbox` is the inbox: one row per LENEX file, pointing at the file in
-- the bucket, with the meet's name and date read at receipt. The file is the
-- source of truth; the dialog reads it again.
--
-- Mail from somebody who is not the club's owner, admin or instructor creates
-- nothing here: the API logs the drop, and a club's table is no place for a
-- stranger's address.

-- ---------------------------------------------------------------------------
-- The address
-- ---------------------------------------------------------------------------

-- 20 characters from the random bytes of two v4 UUIDs, skipping the two bytes
-- of each that carry the version and variant bits. `gen_random_uuid()` is the
-- only CSPRNG in core Postgres (no pgcrypto here); `% 36` biases a character
-- by under a percent, which costs a fraction of a bit of 103.
CREATE FUNCTION new_inbox_token() RETURNS text
LANGUAGE sql
VOLATILE
AS $fn$
  SELECT left(string_agg(substr('abcdefghijklmnopqrstuvwxyz0123456789', get_byte(b, i) % 36 + 1, 1), '' ORDER BY i), 20)
    FROM (SELECT uuid_send(gen_random_uuid()) || uuid_send(gen_random_uuid()) AS b) s,
         generate_series(0, 31) AS i
   WHERE i NOT IN (6, 8, 22, 24);
$fn$;

COMMENT ON FUNCTION new_inbox_token() IS
  'POOLSE-114: a fresh results-inbox token, 20 characters of [a-z0-9]. The one definition, '
  'used by the column default and by regeneration.';

ALTER TABLE organization
  ADD COLUMN meet_inbox_token text NOT NULL DEFAULT new_inbox_token(),
  ADD CONSTRAINT organization_meet_inbox_token_shape CHECK (meet_inbox_token ~ '^[a-z0-9]{20}$');

CREATE UNIQUE INDEX organization_meet_inbox_token_uq ON organization (meet_inbox_token);

COMMENT ON COLUMN organization.meet_inbox_token IS
  'POOLSE-114: the club''s results address is resultados-<token>@<INBOUND_DOMAIN>. '
  'Regenerated by owner or admin; the old one stops at once.';

-- `poolse_app` holds UPDATE on organization column by column (POOLSE-87).
GRANT UPDATE (meet_inbox_token) ON organization TO poolse_app;

-- ---------------------------------------------------------------------------
-- The messages and the files
-- ---------------------------------------------------------------------------

-- A file arriving by email is a stored file like any other, under its own
-- purpose. Compared as text: a value added by ALTER TYPE cannot be used as an
-- enum literal in the transaction that added it.
ALTER TYPE file_purpose ADD VALUE IF NOT EXISTS 'meet_results';

ALTER TABLE stored_file DROP CONSTRAINT stored_file_type;
ALTER TABLE stored_file ADD CONSTRAINT stored_file_type CHECK (
  content_type IN ('application/pdf', 'image/jpeg', 'image/png', 'image/webp')
  OR (
    purpose = 'agreement_document'
    AND content_type = 'application/vnd.openxmlformats-officedocument.wordprocessingml.document'
  )
  -- A `.lef` is XML and a `.lxf` is a zip holding one (POOLSE-114).
  OR (purpose::text = 'meet_results' AND content_type IN ('application/xml', 'application/zip'))
);

CREATE TABLE meet_inbox_message (
  id                    uuid NOT NULL DEFAULT gen_random_uuid(),
  organization_id       uuid NOT NULL REFERENCES organization (id),
  -- Resend's email id (or the dev endpoint's own). The idempotency key.
  provider_message_id   text NOT NULL,
  -- The sender, as matched: one of the club's owners, admins or instructors.
  sender_membership_id  uuid NOT NULL,
  received_from         citext NOT NULL,
  -- How many LENEX files it carried that could be read. Zero is the message
  -- that earned the one "no LENEX found" reply.
  file_count            integer NOT NULL,
  received_at           timestamptz NOT NULL DEFAULT now(),

  PRIMARY KEY (id),
  UNIQUE (organization_id, id),
  UNIQUE (organization_id, provider_message_id),
  FOREIGN KEY (organization_id, sender_membership_id) REFERENCES membership (organization_id, id),
  CONSTRAINT meet_inbox_message_id_bounded CHECK (btrim(provider_message_id) <> '' AND length(provider_message_id) <= 200),
  CONSTRAINT meet_inbox_message_files CHECK (file_count >= 0)
);

COMMENT ON TABLE meet_inbox_message IS
  'POOLSE-114: one row per accepted email to the club''s results address — the idempotency '
  'key on the provider''s message id. Insert-only.';

ALTER TABLE meet_inbox_message ENABLE ROW LEVEL SECURITY;
CREATE POLICY meet_inbox_message_tenant ON meet_inbox_message
  USING (organization_id = current_organization_id())
  WITH CHECK (organization_id = current_organization_id());

REVOKE UPDATE, DELETE ON meet_inbox_message FROM poolse_app;
GRANT SELECT, INSERT ON meet_inbox_message TO poolse_app;

CREATE TYPE meet_inbox_status AS ENUM ('pending', 'imported', 'discarded');

CREATE TABLE meet_inbox (
  id                          uuid NOT NULL DEFAULT gen_random_uuid(),
  organization_id             uuid NOT NULL REFERENCES organization (id),
  message_id                  uuid NOT NULL,
  file_id                     uuid NOT NULL,
  file_name                   text NOT NULL,
  -- Read from the file at receipt, for the list. The dialog reads the file again.
  meet_name                   text NOT NULL,
  meet_starts_on              date NOT NULL,
  status                      meet_inbox_status NOT NULL DEFAULT 'pending',
  meet_id                     uuid,
  imported_at                 timestamptz,
  imported_by_membership_id   uuid,
  discarded_at                timestamptz,
  discarded_by_membership_id  uuid,
  discard_reason              text,
  created_at                  timestamptz NOT NULL DEFAULT now(),
  updated_at                  timestamptz NOT NULL DEFAULT now(),

  PRIMARY KEY (id),
  UNIQUE (organization_id, id),
  UNIQUE (organization_id, file_id),
  FOREIGN KEY (organization_id, message_id) REFERENCES meet_inbox_message (organization_id, id),
  FOREIGN KEY (organization_id, file_id) REFERENCES stored_file (organization_id, id),
  FOREIGN KEY (organization_id, meet_id) REFERENCES swim_meet (organization_id, id),
  FOREIGN KEY (organization_id, imported_by_membership_id) REFERENCES membership (organization_id, id),
  FOREIGN KEY (organization_id, discarded_by_membership_id) REFERENCES membership (organization_id, id),
  CONSTRAINT meet_inbox_file_name CHECK (btrim(file_name) <> '' AND length(file_name) <= 200),
  CONSTRAINT meet_inbox_meet_name CHECK (btrim(meet_name) <> '' AND length(meet_name) <= 200),
  CONSTRAINT meet_inbox_reason_bounded CHECK (discard_reason IS NULL OR length(discard_reason) <= 500),
  -- Each status carries exactly its own facts.
  CONSTRAINT meet_inbox_imported_whole CHECK (
    (status = 'imported') = (meet_id IS NOT NULL AND imported_at IS NOT NULL)),
  CONSTRAINT meet_inbox_discarded_whole CHECK (
    (status = 'discarded') = (discarded_at IS NOT NULL))
);

COMMENT ON TABLE meet_inbox IS
  'POOLSE-114: a LENEX file that arrived by email, waiting to be imported through the '
  'ordinary dialog. pending → imported (links the meet) or discarded (soft, with a reason). '
  'Never deleted, never edited but for its status.';

CREATE INDEX meet_inbox_list ON meet_inbox (organization_id, created_at DESC) WHERE status <> 'discarded';

CREATE TRIGGER meet_inbox_updated_at BEFORE UPDATE ON meet_inbox
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

ALTER TABLE meet_inbox ENABLE ROW LEVEL SECURITY;
CREATE POLICY meet_inbox_tenant ON meet_inbox
  USING (organization_id = current_organization_id())
  WITH CHECK (organization_id = current_organization_id());

REVOKE UPDATE, DELETE ON meet_inbox FROM poolse_app;
GRANT SELECT, INSERT ON meet_inbox TO poolse_app;
GRANT UPDATE (status, meet_id, imported_at, imported_by_membership_id,
              discarded_at, discarded_by_membership_id, discard_reason, updated_at)
  ON meet_inbox TO poolse_app;

-- ---------------------------------------------------------------------------
-- The one read before a tenant is known
-- ---------------------------------------------------------------------------

CREATE FUNCTION meet_inbox_organization(p_token text) RETURNS uuid
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $fn$
DECLARE
  v_org uuid;
BEGIN
  IF p_token IS NULL OR p_token !~ '^[a-z0-9]{20}$' THEN
    RETURN NULL;
  END IF;

  SELECT o.id INTO v_org
    FROM organization o
   WHERE o.meet_inbox_token = p_token
     AND o.archived_at IS NULL
     AND o.suspended_at IS NULL
     AND o.read_only_at IS NULL
     AND NOT ('competition' = ANY (o.disabled_modules));

  RETURN v_org;
END;
$fn$;

COMMENT ON FUNCTION meet_inbox_organization(text) IS
  'POOLSE-114: the club an inbound results email is for, or null — an unknown token, or a '
  'club that is closed, read-only or without the competition module. Its id and nothing else.';

REVOKE ALL ON FUNCTION meet_inbox_organization(text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION meet_inbox_organization(text) TO poolse_app;

